"""Testes da tradução SQLite -> Postgres (rodam sem banco)."""
from produtos_core.banco_pg import traduzir, traduzir_ddl, dividir_script


def test_placeholders_e_funcoes():
    assert traduzir("SELECT * FROM u WHERE email=? AND ativo_ate > strftime('%s','now')")[0] == \
        "SELECT * FROM u WHERE email=%s AND ativo_ate > extract(epoch from now())"


def test_insert_or_ignore_e_replace():
    s, d = traduzir("INSERT OR IGNORE INTO u(email) VALUES(?)")
    assert s == "INSERT INTO u(email) VALUES(%s)" and d == {'ignorar': True}
    s, d = traduzir("INSERT OR REPLACE INTO kv(k,v) VALUES(?,?)")
    assert d == {'substituir': 'kv'}


def test_max_escalar_vira_greatest():
    assert traduzir("UPDATE u SET a=MAX(a, ?) WHERE id=?")[0] == "UPDATE u SET a=GREATEST(a, %s) WHERE id=%s"
    assert traduzir("SELECT MAX(criado) FROM l")[0] == "SELECT MAX(criado) FROM l"


def test_like_e_porcentagem_em_literal():
    assert traduzir("SELECT 1 FROM x WHERE n LIKE ? AND y NOT LIKE '%a%'")[0] == "SELECT 1 FROM x WHERE n ILIKE %s AND y NOT ILIKE '%%a%%'"


def test_ddl():
    assert traduzir_ddl("CREATE TABLE t (id INTEGER PRIMARY KEY, x REAL, b BLOB)") == \
        "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, x DOUBLE PRECISION, b BYTEA)"
    assert traduzir_ddl("ALTER TABLE t ADD COLUMN y TEXT") == "ALTER TABLE t ADD COLUMN IF NOT EXISTS y TEXT"


def test_dividir_script_respeita_aspas():
    assert len(dividir_script("CREATE TABLE a (x TEXT DEFAULT ';');\n-- comentario\nCREATE INDEX i ON a(x);")) == 2
